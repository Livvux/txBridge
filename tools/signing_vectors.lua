local function str(s)
    return '"'..s:gsub('[%c"\\]', function(c)
        local named = {['"']='\\"', ['\\']='\\\\', ['\n']='\\n', ['\r']='\\r', ['\t']='\\t'}
        return named[c] or ('\\u%04x'):format(c:byte())
    end)..'"'
end
local function object(fields, order)
    local parts = {}
    for _, k in ipairs(order) do parts[#parts+1] = '      '..str(k)..': '..str(fields[k]) end
    return '    {\n'..table.concat(parts, ',\n')..'\n    }'
end

local requestOrder = {'name','secret','serverId','keyId','method','path','timestamp','nonce','idempotencyKey','body','bodySha256','canonical','signature'}
local webhookOrder = {'name','secret','serverId','eventId','timestamp','body','bodySha256','canonical','signature'}
local reqOut, hookOut = {}, {}
for _, c in ipairs(requests) do
    c.bodySha256 = C.sha256(c.body)
    c.canonical = table.concat({'TXBRIDGE1',c.serverId,c.keyId,c.method,c.path,c.timestamp,c.nonce,c.idempotencyKey,c.bodySha256}, '\n')
    c.signature = C.hmac(c.secret, c.canonical)
    reqOut[#reqOut+1] = object(c, requestOrder)
end
for _, c in ipairs(webhooks) do
    c.bodySha256 = C.sha256(c.body)
    c.canonical = table.concat({'TXBRIDGE-WEBHOOK1',c.serverId,c.eventId,c.timestamp,c.bodySha256}, '\n')
    c.signature = C.hmac(c.secret, c.canonical)
    hookOut[#hookOut+1] = object(c, webhookOrder)
end
local json = '{\n  "description": "Generated by tools/signing_vectors.lua from the Lua bridge. Fixed public test values only.",\n'
    ..'  "requests": [\n'..table.concat(reqOut, ',\n')..'\n  ],\n'
    ..'  "webhooks": [\n'..table.concat(hookOut, ',\n')..'\n  ]\n}\n'

if arg[1] == '--check' then
    local f = io.open(OUT, 'rb'); local current = f and f:read('a'); if f then f:close() end
    if current ~= json then io.stderr:write(OUT..' is stale; run lua5.4 tools/signing_vectors.lua\n'); os.exit(1) end
    print(OUT..' is up to date ('..#requests..' requests, '..#webhooks..' webhooks)')
else
    local f = assert(io.open(OUT, 'wb')); f:write(json); f:close()
    print('wrote '..OUT)
end
